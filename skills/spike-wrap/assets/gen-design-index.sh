#!/usr/bin/env bash
# Generate docs/designs/README.md from the frontmatter of every
# docs/designs/agents/<topic>/design.md.
#
# The index is generated, never hand-edited: a hand-maintained table is the first place
# parallel branches collide, because every branch inserts a row at the same spot.
# Each design.md's title / status / summary is the single source of truth.
#
#   bash gen-design-index.sh          # regenerate (run from anywhere inside the repo)
#   bash gen-design-index.sh --check  # check only (for CI): fails if stale or a field is missing
#
# Localize the HEADER lines below to the project's working language if you like.
set -euo pipefail

root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
agents="$root/docs/designs/agents"
out="$root/docs/designs/README.md"
check=0
[[ "${1:-}" == "--check" ]] && check=1

HEADER_TITLE="# Design docs"
HEADER_NOTE="Generated by gen-design-index.sh from each design.md's frontmatter — do not edit by hand. Docs describe the current state; when the implementation changes, rewrite the affected section in place instead of appending."
HEADER_ROW="| Topic | Title | Status | Summary |"

# Read a single-line scalar from the frontmatter (multi-line values unsupported — summary must be one line).
field() {
  awk -v key="$2" '
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { exit }
    NR > 1 && index($0, key ":") == 1 {
      v = substr($0, length(key) + 2)
      sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
      if (v ~ /^".*"$/ || v ~ /^'\''.*'\''$/) v = substr(v, 2, length(v) - 2)
      gsub(/\|/, "\\|", v)
      print v; exit
    }' "$1"
}

[[ -d "$agents" ]] || { echo "no $agents directory" >&2; exit 1; }

errors=()
rows=()
for dir in "$agents"/*/; do
  topic="$(basename "$dir")"
  doc="$dir/design.md"
  if [[ ! -f "$doc" ]]; then
    errors+=("$topic: missing design.md")
    continue
  fi
  title="$(field "$doc" title)"
  status="$(field "$doc" status)"
  summary="$(field "$doc" summary)"
  for k in title status summary; do
    [[ -n "${!k}" ]] || errors+=("$topic/design.md: frontmatter missing $k")
  done
  case "$status" in
    implemented|partial|planned|paused|abandoned|"") ;;
    *) errors+=("$topic/design.md: status '$status' is not one of implemented|partial|planned|paused|abandoned") ;;
  esac
  rows+=("| [$topic](agents/$topic/design.md) | $title | $status | $summary |")
done

if ((${#errors[@]})); then
  printf '✗ %s\n' "${errors[@]}" >&2
  exit 1
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "$HEADER_TITLE"
  echo
  echo "<!-- $HEADER_NOTE -->"
  echo
  echo "$HEADER_ROW"
  echo "|---|---|---|---|"
  printf '%s\n' "${rows[@]}"
} > "$tmp"

if ((check)); then
  if ! cmp -s "$tmp" "$out"; then
    echo "✗ docs/designs/README.md is stale — run gen-design-index.sh" >&2
    diff -u "$out" "$tmp" >&2 || true
    exit 1
  fi
  echo "✓ design index is up to date (${#rows[@]} topics)"
else
  cp "$tmp" "$out"
  echo "✓ wrote docs/designs/README.md (${#rows[@]} topics)"
fi
